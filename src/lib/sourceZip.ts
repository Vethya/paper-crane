import { join } from 'node:path'
import Archiver from 'archiver'
import { stripIndent } from 'common-tags'
import getTemplateData from './templates'
import { templateAssetEntries } from './latexAssets'
import { FormValues } from '../types'

/**
 * Builds a ZIP of the resume's LaTeX source: resume.tex, a README, and the
 * template's class, style and font files at the paths the browser compiler
 * uses, so the extracted folder compiles as it is.
 *
 * @param formData The resume form values.
 * @param publicDir The folder that holds the app's public files.
 *
 * @return A promise that resolves to the ZIP contents.
 */
export function buildSourceZip(
  formData: FormValues,
  publicDir = join(process.cwd(), 'public')
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const { texDoc, opts } = getTemplateData(formData)
    const zip = Archiver('zip')

    const chunks: Buffer[] = []
    zip.on('data', (chunk: Buffer) => chunks.push(chunk))
    zip.on('warning', reject)
    zip.on('error', reject)
    zip.on('end', () => resolve(Buffer.concat(chunks)))

    zip.append(texDoc, { name: 'resume.tex' })
    zip.append(makeReadme(formData.selectedTemplate, opts.cmd), {
      name: 'README.md'
    })
    for (const [name, publicPath] of templateAssetEntries(opts)) {
      zip.file(join(publicDir, publicPath), { name })
    }

    zip.finalize()
  })
}

/**
 * Generates a README to include in the output zip.
 * It details how to use the generated LaTeX source code.
 *
 * @param template The specified resume template.
 * @param cmd The LaTeX command that is used to generate the PDF.
 *
 * @return The generated README text.
 */
function makeReadme(template: number, cmd: string): string {
  return stripIndent`
    # Paper Crane Template ${template}
    > LaTeX code generated by Paper Crane
    ## Usage
    To generate a PDF from this LaTeX code, navigate to this folder in a terminal and run:
        ${cmd} resume.tex
    ## Requirements
    You will need to have \`${cmd}\` installed on your machine.
    Alternatively, you can use a site like [ShareLaTeX](https://sharelatex.com) to build and edit your LaTeX instead.
  `
}
